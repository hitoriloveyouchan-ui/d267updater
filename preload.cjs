// The only bridge between the page and the main process.
const { contextBridge, ipcRenderer } = require('electron');

const call = (channel, ...args) => ipcRenderer.invoke(channel, ...args);

contextBridge.exposeInMainWorld('api', {
  init: () => call('app:init'),
  chooseGame: () => call('game:choose'),
  state: () => call('cos:state'),
  slots: () => call('cos:slots'),
  equipped: () => call('cos:equipped'),
  clearAll: () => call('cos:clearAll'),
  apply: () => call('cos:apply'),
  pick: (slot, itemId) => call('cos:pick', slot, itemId),
  emblems: () => call('cos:emblems'),
  pickFx: (slot, itemId, effects) => call('cos:pickFx', slot, itemId, effects || []),
  slotFx: (slot, effects) => call('cos:slotFx', slot, effects || []),
  pickEmblem: (slot, itemId) => call('cos:pickEmblem', slot, itemId),
  heroes: () => call('hero:list'),
  heroSlots: (heroId) => call('hero:slots', heroId),
  heroPick: (slotId, itemId, effects) => call('hero:pick', slotId, itemId, effects || []),
  heroSet: (setId) => call('hero:set', setId),
  heroReset: (heroId) => call('hero:reset', heroId),
  heroGem: (color) => call('hero:gem', color),
  spellList: () => call('spell:list'),
  spellPick: (ability, icon) => call('spell:pick', ability, icon),
  iconsSpells: (names) => call('icons:spells', names),
  iconsItems: (ids) => call('icons:items', ids),
  iconsHeroes: (ids) => call('icons:heroes', ids),
  settings: () => call('settings:get'),
  setSetting: (key, value) => call('settings:set', key, value),
  detectGame: () => call('game:detect'),
  toolInstall: () => call('tools:install', 'vrf'),
  toolRemove: () => call('tools:remove', 'vrf'),
  clearCache: () => call('cache:clear'),
  openDataFolder: () => call('shell:dataFolder'),
  openExternal: (url) => call('shell:external', url),
  checkUpdate: () => call('update:check'),
  installUpdate: () => call('update:install'),
  onUpdate: (cb) => ipcRenderer.on('update:state', (_e, state) => cb(state)),
  onToolProgress: (cb) => ipcRenderer.on('tools:progress', (_e, evt) => cb(evt)),
  openModsFolder: () => call('shell:modsFolder'),
  play: () => call('shell:play'),
  win: {
    min: () => ipcRenderer.send('win:min'),
    max: () => ipcRenderer.send('win:max'),
    close: () => ipcRenderer.send('win:close'),
  },
});
